STEP6: Create DEV Snowpipe
**************************
CREATE OR REPLACE PIPE DEV_DB.STAGE.EMP_SNOWPIPE
AUTO_INGEST = TRUE
AS
COPY INTO DEV_DB.RAW.EMP_DATA_RAW
(EMP_ID,NAME,TAX,SALARY,DOB,COUNTRY,FILE_NAME,LOAD_TIMESTAMP,PIPE_NAME)
FROM
(SELECT $1, $2, $3, $4, $5, $6, METADATA$FILENAME, CURRENT_TIMESTAMP(), 'EMP_SNOWPIPE'
    FROM @DEV_DB.STAGE.EMP_EXT_STAGE
)
ON_ERROR = 'SKIP_FILE';

STEP7: Create Stream (DEV)
**************************
CREATE OR REPLACE STREAM DEV_DB.STAGE.EMP_STREAM
ON TABLE DEV_DB.RAW.EMP_DATA_RAW
APPEND_ONLY = TRUE;

STEP8: Create Curated Table (DEV)
**********************************
CREATE OR REPLACE TABLE DEV_DB.CURATED.EMP_DATA (
    EMP_ID     VARCHAR PRIMARY KEY,
    NAME       VARCHAR,
    TAX        NUMBER(10,2),
    SALARY     NUMBER(12,2),
    DOB        TIMESTAMP_NTZ,
    COUNTRY    VARCHAR,
    UPDATED_AT TIMESTAMP_NTZ
);

STEP9: Create Merge Task (DEV — Faster Schedule)
********************************************
In DEV we use 1 minute for quick testing.

CREATE OR REPLACE TASK DEV_DB.STAGE.EMP_MERGE_TASK
WAREHOUSE = COMPUTE_WH
SCHEDULE = '1 MINUTE'
WHEN SYSTEM$STREAM_HAS_DATA('DEV_DB.STAGE.EMP_STREAM')
AS
MERGE INTO DEV_DB.CURATED.EMP_DATA T
USING DEV_DB.STAGE.EMP_STREAM S
ON T.EMP_ID = S.EMP_ID

WHEN MATCHED THEN
UPDATE SET
    NAME = S.NAME,
    TAX = S.TAX,
    SALARY = S.SALARY,
    DOB = S.DOB,
    COUNTRY = S.COUNTRY,
    UPDATED_AT = CURRENT_TIMESTAMP()

WHEN NOT MATCHED THEN
INSERT
(
    EMP_ID, NAME, TAX, SALARY, DOB, COUNTRY, UPDATED_AT
)
VALUES
(
    S.EMP_ID, S.NAME, S.TAX, S.SALARY, S.DOB, S.COUNTRY, CURRENT_TIMESTAMP()
);

Enable task:
ALTER TASK DEV_DB.STAGE.EMP_MERGE_TASK RESUME;
