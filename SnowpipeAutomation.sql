STEP4: Create File Format (Strict but DEV-Friendly)
**************************************
CREATE OR REPLACE FILE FORMAT DEV_DB.STAGE.CSV_EMP_FORMAT
TYPE = CSV
FIELD_DELIMITER = ','
SKIP_HEADER = 1
TRIM_SPACE = TRUE
FIELD_OPTIONALLY_ENCLOSED_BY = '"'
NULL_IF = ('NULL', 'null', '')
EMPTY_FIELD_AS_NULL = TRUE
