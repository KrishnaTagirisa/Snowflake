STEP1: Create DEV Database & Schemas
**************************************
CREATE DATABASE IF NOT EXISTS DEV_DB;

CREATE SCHEMA IF NOT EXISTS DEV_DB.RAW;
CREATE SCHEMA IF NOT EXISTS DEV_DB.STAGE;
CREATE SCHEMA IF NOT EXISTS DEV_DB.CURATED;

STEP2: Create RAW Table (Append Only + Metadata)
**************************************
CREATE OR REPLACE TABLE DEV_DB.RAW.EMP_DATA_RAW (
    EMP_ID           VARCHAR,
    NAME             VARCHAR,
    TAX              NUMBER(10,2),
    SALARY           NUMBER(12,2),
    DOB              TIMESTAMP_NTZ,
    COUNTRY          VARCHAR,
    
    -- Metadata Columns
    FILE_NAME        VARCHAR,
    LOAD_TIMESTAMP   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PIPE_NAME        VARCHAR
);

